def normalize(x, x_max=None, x_min=None):
    if x_max is None:
        x_max = x.max(axis=0)
        x_min = x.min(axis=0)
    x_range = (x_max - x_min) / 2.0
    x_avg   = (x_max + x_min) / 2.0
    return (x - x_avg) / x_range, x_max, x_min

