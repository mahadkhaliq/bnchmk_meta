class TransformerSurrogate(nn.Module):
    """Reproduction of Deng et al. 2021 hybrid transformer.
    Head MLP -> reshape to sequence -> transformer encoder -> tail MLP."""
    def __init__(self, dim_g=14, dim_s=2001,
                 head_linear=(14, 168), seq_len=12, feature_channels=14,
                 nhead=2, dim_ff=64, num_layers=2, tail_linear=()):
        super().__init__()
        assert head_linear[-1] == seq_len * feature_channels, \
            "head output must equal seq_len * feature_channels"
        self.seq_len = seq_len
        self.feature_channels = feature_channels

        self.head_linears = nn.ModuleList()
        self.head_bns = nn.ModuleList()
        for i in range(len(head_linear) - 1):
            self.head_linears.append(nn.Linear(head_linear[i], head_linear[i+1]))
            self.head_bns.append(nn.BatchNorm1d(head_linear[i+1]))

        enc_layer = nn.TransformerEncoderLayer(
            d_model=feature_channels, nhead=nhead,
            dim_feedforward=dim_ff, batch_first=True)
        self.encoder = nn.TransformerEncoder(enc_layer, num_layers=num_layers)

        last_node = seq_len * feature_channels
        self.tail_linears = nn.ModuleList()
        self.tail_bns = nn.ModuleList()
        dims = [last_node] + list(tail_linear) + [dim_s] if tail_linear else [last_node, dim_s]
        for i in range(len(dims) - 1):
            self.tail_linears.append(nn.Linear(dims[i], dims[i+1]))
            self.tail_bns.append(nn.BatchNorm1d(dims[i+1]))

    def forward(self, G):
        out = G
        for fc, bn in zip(self.head_linears, self.head_bns):
            out = F.relu(bn(fc(out)))
        out = out.view(out.size(0), self.seq_len, self.feature_channels)
        out = self.encoder(out)
        out = out.reshape(out.size(0), -1)
        for i, (fc, bn) in enumerate(zip(self.tail_linears, self.tail_bns)):
            if i != len(self.tail_linears) - 1:
                out = F.relu(bn(fc(out)))
            else:
                out = fc(out)
        return out

