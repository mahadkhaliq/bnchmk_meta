class TransformerModel(nn.Module):
    def __init__(self, head_linear, sequence_length, feature_channel_num,
                 nhead, dim_fc_encoder, num_encoder_layer, dim_s):
        super().__init__()
        self.sequence_length = sequence_length

        # ---- HEAD: MLP that expands 14 -> 6144 (manufactures the token sequence) ----
        self.head_linears    = nn.ModuleList([])
        self.head_bn_linears = nn.ModuleList([])
        for i in range(len(head_linear) - 1):
            self.head_linears.append(nn.Linear(head_linear[i], head_linear[i+1]))
            self.head_bn_linears.append(nn.BatchNorm1d(head_linear[i+1]))

        # ---- BODY: stack of Transformer encoder layers ----
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=feature_channel_num,
            nhead=nhead,
            dim_feedforward=dim_fc_encoder,
            batch_first=True,           # input is (batch, seq, features)
        )
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_encoder_layer)

        # ---- TAIL: single Linear from flattened sequence to spectrum ----
        self.tail = nn.Linear(sequence_length * feature_channel_num, dim_s)

    def forward(self, g):
        # head MLP
        out = g
        for i, (fc, bn) in enumerate(zip(self.head_linears, self.head_bn_linears)):
            if i < len(self.head_linears) - 1:
                out = F.relu(bn(fc(out)))   # all but last: Linear + BN + ReLU
            else:
                out = fc(out)               # last head layer: bare Linear
        # reshape (B, 6144) -> (B, 12, 512): manufacture the token sequence
        out = out.view(out.size(0), self.sequence_length, -1)
        # transformer encoder (no positional encoding)
        out = self.transformer_encoder(out)
        # flatten (B, 12, 512) -> (B, 6144), then project to spectrum
        out = out.reshape(out.size(0), -1)
        out = self.tail(out)
        return out

