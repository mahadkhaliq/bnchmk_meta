class MLP(nn.Module):
    def __init__(self, layers):
        super(MLP, self).__init__()
        self.linears = nn.ModuleList([])
        self.bn_linears = nn.ModuleList([])

        for i in range(len(layers) - 1):
            self.linears.append(nn.Linear(layers[i], layers[i+1]))
            # Batch norm matches the output dimension of the linear layer
            self.bn_linears.append(nn.BatchNorm1d(layers[i+1]))

    def forward(self, g):
        out = g
        for i, (fc, bn) in enumerate(zip(self.linears, self.bn_linears)):
            if i < len(self.linears) - 1:
                # Hidden layers: Linear -> BatchNorm -> ReLU
                # Note: If passing 3D tensors [Batch, Seq, Features],
                # BatchNorm1d expects [Batch, Features, Seq], so we must transpose
                if out.dim() == 3:
                    out = fc(out)
                    out = out.transpose(1, 2) # [B, Features, 4]
                    out = bn(out)
                    out = out.transpose(1, 2) # Back to [B, 4, Features]
                    out = F.relu(out)
                else:
                    out = F.relu(bn(fc(out)))
            else:
                # Final layer: Just Linear
                out = fc(out)

        # If the input was 3D (Neighborhood processing), pool it down to 2D
        if out.dim() == 3:
            out = out.mean(dim=1)

        return out

