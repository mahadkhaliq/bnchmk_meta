"""
Plot one supercell as 4 ellipses showing the actual geometry of the cylinders.
Each ellipse is drawn at its (rx, ry) size, rotated by theta, and colored
differently to distinguish the 4 cylinders.
"""

import matplotlib.pyplot as plt
from matplotlib.patches import Ellipse, Rectangle
import numpy as np


def plot_supercell(grid, sample_idx=0, ax=None, show_labels=True, show_axes=True):
    """Draw the 4 cylinders of one supercell from a top-down view.

    Args:
        grid: array of shape (n, 2, 2, 5)
        sample_idx: which sample to plot
        ax: optional matplotlib axis to draw on
        show_labels: whether to label each cylinder
        show_axes: whether to show axis ticks and labels
    """
    if ax is None:
        fig, ax = plt.subplots(figsize=(6, 6))

    # Get the period (the size of the supercell)
    p = grid[sample_idx, 0, 0, 4]
    h = grid[sample_idx, 0, 0, 3]

    # Position each cylinder at its grid cell center
    # 2x2 grid with cell size p/2 each, so centers are at p/4 and 3p/4
    cell_centers = {
        (0, 0): (p/4, 3*p/4),     # top-left  → in plot, top-left
        (0, 1): (3*p/4, 3*p/4),   # top-right
        (1, 0): (p/4, p/4),        # bottom-left
        (1, 1): (3*p/4, p/4),      # bottom-right
    }

    # One distinct color per cylinder
    colors = ['#378ADD', '#1D9E75', '#D85A30', '#7F77DD']

    # Draw the substrate (the supercell boundary)
    ax.add_patch(Rectangle((0, 0), p, p,facecolor='#f0f0f0',edgecolor='gray',linewidth=1.5,linestyle='--'))

    # Draw each cylinder as an ellipse
    for i in range(4):
        r = i // 2
        c = i % 2
        rx = grid[sample_idx, r, c, 0]
        ry = grid[sample_idx, r, c, 1]
        theta_rad = grid[sample_idx, r, c, 2]
        theta_deg = np.degrees(theta_rad)

        cx, cy = cell_centers[(r, c)]

        # Ellipse expects full width/height (= 2 * radius), and angle in degrees
        ellipse = Ellipse(xy=(cx, cy),width=2 * rx,height=2 * ry,angle=theta_deg,facecolor=colors[i],edgecolor='black',linewidth=1.2,alpha=0.75,)
        ax.add_patch(ellipse)
        if show_labels:
            ax.annotate(f'{i+1}',
                        xy=(cx, cy),
                        ha='center', va='center',
                        fontsize=12, fontweight='bold',
                        color='white')

    ax.set_xlim(-0.05 * p, 1.05 * p)
    ax.set_ylim(-0.05 * p, 1.05 * p)
    ax.set_aspect('equal')

    if show_axes:
        ax.set_xlabel('x (μm)')
        ax.set_ylabel('y (μm)')
        ax.set_title(f'Sample {sample_idx} supercell top view (h={h:.3f}, p={p:.3f})')
    else:
        ax.set_xticks([])
        ax.set_yticks([])

def plot_multiple_samples(grid, sample_indices, ncols=4):
    """Plot multiple supercells in a grid layout for comparison."""
    n = len(sample_indices)
    nrows = (n + ncols - 1) // ncols
    fig, axes = plt.subplots(nrows, ncols, figsize=(4*ncols, 4*nrows))
    if nrows == 1 and ncols == 1:
        axes = np.array([axes])
    axes = np.array(axes).flatten()

    for ax_idx, sample_idx in enumerate(sample_indices):
        plot_supercell(grid, sample_idx, ax=axes[ax_idx], show_axes=False)
        axes[ax_idx].set_title(f'Sample {sample_idx}', fontsize=11)

    # Hide unused axes
    for ax_idx in range(len(sample_indices), len(axes)):
        axes[ax_idx].axis('off')

    plt.tight_layout()
    plt.show()

