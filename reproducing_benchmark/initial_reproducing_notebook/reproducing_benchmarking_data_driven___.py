def build_grid(g, x_max=None, x_min=None):
    """
    Take raw geometry array (n, 14) and return normalized grid (n, 2, 2, 5).
    Normalizes each of the 14 raw columns to [-1, 1] BEFORE reshaping.
    """
    # normalize the 14 columns first (same min-max as baseline)
    if x_max is None:
        x_max = g.max(axis=0)
        x_min = g.min(axis=0)
    x_range = (x_max - x_min) / 2.0
    x_avg   = (x_max + x_min) / 2.0
    x_range = np.where(x_range == 0, 1e-8, x_range)
    g = (g - x_avg) / x_range

    # reshape to grid
    n = g.shape[0]
    grid = np.zeros((n, 2, 2, 5), dtype='float32')
    for i in range(4):
        r = i // 2
        c = i % 2
        grid[:, r, c, 0] = g[:, 2 + 2*i]   # rx
        grid[:, r, c, 1] = g[:, 3 + 2*i]   # ry
        grid[:, r, c, 2] = g[:, 10 + i]    # theta
        grid[:, r, c, 3] = g[:, 0]         # h
        grid[:, r, c, 4] = g[:, 1]         # p
    return grid, x_max, x_min

