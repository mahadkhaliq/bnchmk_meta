def train_one_epoch(model, loader, optimizer, criterion, device):
    model.train()
    total = 0.0
    for g, s in loader:
        g, s = g.to(device), s.to(device)
        optimizer.zero_grad()
        loss = criterion(model(g), s)
        loss.backward()
        optimizer.step()
        total += loss.item()
    return total / len(loader)

def evaluate(model, loader, criterion, device):
    model.eval()
    total = 0.0
    with torch.no_grad():
        for g, s in loader:
            g, s = g.to(device), s.to(device)
            total += criterion(model(g), s).item()
    return total / len(loader)

