"""
Plot a supercell (or padded supercell) as a grid of ellipses.
The function automatically detects the grid size from the array shape.

Works for any (n, N, N, 5) array — original 2x2 grid, padded 4x4 grid,
larger grids, etc.
"""

import matplotlib.pyplot as plt
from matplotlib.patches import Ellipse, Rectangle
import numpy as np

def plot_grid(grid, sample_idx=0, ax=None, title=None, show_labels=True, show_axes=True, original_N=None):
    if ax is None:
        fig, ax = plt.subplots(figsize=(6, 6))

    N = grid.shape[1]
    p = grid[sample_idx, 0, 0, 4]
    h = grid[sample_idx, 0, 0, 3]

    # Each cell takes up p/N_orig of physical space.
    # If padded, the whole plot is N/N_orig * p wide.
    if original_N is not None:
        cell_size = p / original_N
        pad = (N - original_N) // 2
        plot_extent = N * cell_size
    else:
        cell_size = p / N
        pad = 0
        plot_extent = p

    # Colors for the original cells (consistent across original and padded)
    n_orig_cells = (original_N if original_N is not None else N) ** 2
    cmap = plt.cm.tab10 if n_orig_cells <= 10 else plt.cm.tab20
    base_colors = [cmap(i % cmap.N) for i in range(n_orig_cells)]

    # Draw the boundary of the original (solid line) and total area (dashed)
    if original_N is not None:
        # Total padded area
        ax.add_patch(Rectangle((0, 0), plot_extent, plot_extent,facecolor='#fafafa',edgecolor='lightgray',linewidth=0.8, linestyle=':'))
        # Original area sits in the middle
        ax.add_patch(Rectangle((pad * cell_size, pad * cell_size), p, p,facecolor='#f0f0f0',edgecolor='black',linewidth=2,linestyle='-',zorder=0))
    else:
        ax.add_patch(Rectangle((0, 0), plot_extent, plot_extent,facecolor='#f0f0f0',edgecolor='gray',linewidth=1.5,linestyle='--'))

    # Draw each cylinder
    for i in range(N * N):
        r = i // N
        c = i % N
        rx = grid[sample_idx, r, c, 0]
        ry = grid[sample_idx, r, c, 1]
        theta_rad = grid[sample_idx, r, c, 2]
        theta_deg = np.degrees(theta_rad)

        # Cell center: row 0 at top, so flip y
        cx = c * cell_size + cell_size / 2
        cy = (N - 1 - r) * cell_size + cell_size / 2

        # Determine color and whether this cell is a wrapped copy
        if original_N is not None:
            # Map (r, c) of padded grid back to source position in original
            src_r = (r - pad) % original_N
            src_c = (c - pad) % original_N
            src_idx = src_r * original_N + src_c
            color = base_colors[src_idx]
            is_original = (pad <= r < pad + original_N) and (pad <= c < pad + original_N)
            label = f'{src_idx + 1}'
        else:
            color = base_colors[i]
            is_original = True
            label = f'{i + 1}'

        ellipse = Ellipse(
            xy=(cx, cy),
            width=2 * rx,
            height=2 * ry,
            angle=theta_deg,
            facecolor=color,
            edgecolor='black',
            linewidth=1.2 if is_original else 0.6,
            alpha=0.85 if is_original else 0.4,
        )
        ax.add_patch(ellipse)

        if show_labels:
            fontsize = max(8, 14 - N)
            ax.annotate(label,
                        xy=(cx, cy),ha='center', va='center',fontsize=fontsize,fontweight='bold' if is_original else 'normal',color='white' if is_original else 'gray')

    margin = 0.05 * plot_extent
    ax.set_xlim(-margin, plot_extent + margin)
    ax.set_ylim(-margin, plot_extent + margin)
    ax.set_aspect('equal')

    if title is None:
        title = f'Sample {sample_idx} — {N}×{N} grid (h={h:.3f}, p={p:.3f})'
    ax.set_title(title)

    if show_axes:
        ax.set_xlabel('x (μm)')
        ax.set_ylabel('y (μm)')
    else:
        ax.set_xticks([])
        ax.set_yticks([])

